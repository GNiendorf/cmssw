#!/usr/bin/env python3
"""Export a train_otpull.py model to src/alpaka/OTPullNeuralNetworkWeights.h: the standardisation is folded into layer 1
(w' = w / std, b' = b - sum(w * mean / std)); the clip bounds are written in raw input units (NeuralNetwork.h otpulldnn
clips before layer 1). Checks that the header reproduces the torch model on random rows inside the clip box.
  python3 export_otpull.py models/otpull_v1.json [--out ../../../../src/alpaka/OTPullNeuralNetworkWeights.h]
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import FEATURES, NIN, mlp_numpy, read_header  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def fmt(v):
    s = f"{float(v):.9g}"
    return (s if ("." in s or "e" in s) else s + ".") + "f"


def arr1(name, v, per=8):
    rows = [", ".join(fmt(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return f"  HOST_DEVICE_CONSTANT float {name}[{len(v)}] = {{\n      " + ",\n      ".join(rows) + "};\n"


def arr2(name, m, per=8):
    out = f"  HOST_DEVICE_CONSTANT float {name}[{m.shape[0]}][{m.shape[1]}] = {{\n"
    rows = []
    for r in m:
        chunks = [", ".join(fmt(x) for x in r[i:i + per]) for i in range(0, len(r), per)]
        rows.append("      {" + ",\n       ".join(chunks) + "}")
    return out + ",\n".join(rows) + "};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("--out", default=os.path.join(HERE, "../../../../src/alpaka/OTPullNeuralNetworkWeights.h"))
    a = ap.parse_args()
    m = json.load(open(a.model))
    assert m["features"] == FEATURES, "feature list differs from common.py"
    sd = {k: np.array(v, np.float64) for k, v in m["state_dict"].items()}
    w1, b1 = sd["0.weight"], sd["0.bias"]  # [H, NIN]
    w2, b2 = sd["2.weight"], sd["2.bias"]
    w3, b3 = sd["4.weight"], sd["4.bias"]
    mu, std = np.array(m["mean"]), np.array(m["std"])
    w1f = w1 / std[None, :]
    b1f = b1 - (w1 * (mu / std)[None, :]).sum(axis=1)
    H = w1.shape[0]
    lo, hi = np.array(m["clip_lo"]), np.array(m["clip_hi"])
    txt = ("#ifndef RecoTracker_LSTCore_src_alpaka_OTPullNeuralNetworkWeights_h\n"
           "#define RecoTracker_LSTCore_src_alpaka_OTPullNeuralNetworkWeights_h\n\n"
           "#include <alpaka/alpaka.hpp>\n\n"
           "#include \"FWCore/Utilities/interface/HostDeviceConstant.h\"\n\n"
           "// Generated by standalone/analysis/DNN/otpull_score/export_otpull.py (model tag %s); do not edit.\n"
           "namespace ALPAKA_ACCELERATOR_NAMESPACE::lst::dnn::otpulldnn {\n"
           "  constexpr unsigned int kInputFeatures = %d;\n"
           "  constexpr unsigned int kHiddenFeatures = %d;\n" % (m["tag"], NIN, H))
    txt += arr1("kClipLo", lo) + arr1("kClipHi", hi)
    txt += arr1("bias_layer1", b1f) + arr2("wgtT_layer1", w1f.T)
    txt += arr1("bias_layer2", b2) + arr2("wgtT_layer2", w2.T)
    txt += arr1("bias_output_layer", b3) + arr2("wgtT_output_layer", w3.T)
    txt += "}  // namespace ALPAKA_ACCELERATOR_NAMESPACE::lst::dnn::otpulldnn\n\n#endif\n"
    open(a.out, "w").write(txt)
    # CMSSW code format (clang-format of the release, available after cmsenv)
    import shutil
    import subprocess
    style = os.path.join(os.environ.get("CMSSW_RELEASE_BASE", ""), "src/.clang-format")
    if shutil.which("clang-format") and os.path.exists(style):
        subprocess.run(["clang-format", f"--style=file:{style}", "-i", a.out], check=True)
    else:
        print("note: clang-format of the release not found (run cmsenv): header left unformatted")
    # check: header (float32, folded) vs the unfolded float64 model
    rng = np.random.default_rng(1)
    X = lo + (hi - lo) * rng.random((20000, NIN))
    ref = np.maximum(np.maximum(((np.clip(X, lo, hi) - mu) / std) @ w1.T + b1, 0) @ w2.T + b2, 0) @ w3.T + b3
    clo, chi, layers = read_header(a.out)
    got = mlp_numpy(X.astype(np.float32), layers, clo, chi)
    d = np.abs(got - ref[:, 0])
    print(f"wrote {a.out}: max |header - model| logit {d.max():.2e} (median {np.median(d):.1e}) on 20000 rows")
    assert d.max() < 1e-3


if __name__ == "__main__":
    main()
